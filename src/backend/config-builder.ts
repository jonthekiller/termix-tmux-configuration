/**
 * Turns an effective tmux configuration into the artifacts that reach a host:
 * the config file pushed to ~/.termix/tmux.conf and the per-session commands
 * run against live sessions.
 *
 * Pure string work: no SSH, no ctx, fully unit-testable.
 */

import type { TmuxEffectiveConfig } from "./option-catalog.js";

/** The file the generated config is pushed to, in the target user's home. */
export const CONFIG_FILE_PATH = "~/.termix/tmux.conf";

/**
 * Quotes a value for a tmux config file line. Double quotes with the two
 * characters tmux would interpret inside them escaped; `;` and `#` are safe
 * inside quotes, which matters because `;` is a command separator and `#` a
 * comment in a conf file.
 */
export function tmuxConfQuote(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** Quotes a value for the shell (POSIX single-quote escaping). */
export function shellEscape(value: string): string {
  return "'" + value.replace(/'/g, "'\\''") + "'";
}

/**
 * The commands inside one `tmux -u` invocation, chained with `\;`, that set
 * one session's options. `-q` keeps an older tmux that lacks an option from
 * aborting the whole chain. The `=name` target is tmux's exact-match syntax,
 * so a session named like a prefix of another is never mistargeted.
 */
export function perSessionArgs(
  config: TmuxEffectiveConfig,
  sessionName: string,
): string {
  const target = shellEscape(`=${sessionName}`);
  const commands = [
    `set-option -q -t ${target} history-limit ${config.historyLimit}`,
    `set-option -q -t ${target} mouse ${config.mouse}`,
    `set-option -q -t ${target} renumber-windows ${config.renumberWindows}`,
    `set-option -q -t ${target} set-clipboard ${config.setClipboard}`,
    `set-option -q -t ${target} remain-on-exit ${config.remainOnExit}`,
    `set-option -q -t ${target} exit-empty ${config.exitEmpty}`,
  ];
  return commands.join(" \\; ");
}

/** One `tmux -u` invocation applying the global options and environment. */
export function globalArgs(config: TmuxEffectiveConfig): string {
  const commands = [
    `set-option -g -q history-limit ${config.historyLimit}`,
    `set-option -g -q mouse ${config.mouse}`,
    `set-option -g -q renumber-windows ${config.renumberWindows}`,
    `set-option -g -q set-clipboard ${config.setClipboard}`,
    `set-option -g -q remain-on-exit ${config.remainOnExit}`,
    `set-option -g -q exit-empty ${config.exitEmpty}`,
  ];
  for (const [name, value] of Object.entries(config.customOptions)) {
    commands.push(`set-option -g -q ${name} ${shellEscape(value)}`);
  }
  for (const [name, value] of Object.entries(config.environment)) {
    commands.push(`set-environment -g ${name} ${shellEscape(value)}`);
  }
  return commands.join(" \\; ");
}

/**
 * The tmux config file pushed to the host. Global options, then the
 * environment, then the user's snippet verbatim. `tmux source-file` on this
 * file replays all of it, so the file is idempotent by construction.
 */
export function buildConfigFile(config: TmuxEffectiveConfig): string {
  const lines: string[] = [
    "# Generated by Termix (tmux-configuration plugin).",
    "# Safe to delete: the next apply recreates it. Do not edit by hand;",
    "# your changes are overwritten on the next application.",
    "",
    `set-option -g history-limit ${config.historyLimit}`,
    `set-option -g mouse ${config.mouse}`,
    `set-option -g renumber-windows ${config.renumberWindows}`,
    `set-option -g set-clipboard ${config.setClipboard}`,
    `set-option -g remain-on-exit ${config.remainOnExit}`,
    `set-option -g exit-empty ${config.exitEmpty}`,
  ];

  for (const [name, value] of Object.entries(config.customOptions)) {
    lines.push(`set-option -g ${name} ${tmuxConfQuote(value)}`);
  }
  for (const [name, value] of Object.entries(config.environment)) {
    lines.push(`set-environment -g ${name} ${tmuxConfQuote(value)}`);
  }

  const snippet = config.configSnippet.trim();
  if (snippet) {
    lines.push("", "# User snippet");
    lines.push(snippet);
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * The shell command that writes the config file on the host. A quoted
 * heredoc: no expansion of the content, ever — the file is data, not shell.
 * The delimiter is randomized so a snippet containing a delimiter line
 * cannot terminate the document early.
 */
export function pushFileCommand(content: string): string {
  const delimiter = `TMUX_CONF_EOF_${Math.random().toString(16).slice(2, 10).toUpperCase()}`;
  return [
    "mkdir -p ~/.termix",
    `cat > ${CONFIG_FILE_PATH} <<'${delimiter}'`,
    content,
    delimiter,
  ].join("\n");
}

/**
 * What a preview shows: the file content and the commands that would run,
 * without touching the host.
 */
export interface ConfigPreview {
  file: string;
  fileCommand: string;
  globalCommand: string;
  /** One entry per live session; empty when the host has no sessions yet. */
  perSessionCommands: Array<{ sessionName: string; command: string }>;
}

export function buildPreview(
  config: TmuxEffectiveConfig,
  sessionNames: string[],
): ConfigPreview {
  return {
    file: buildConfigFile(config),
    fileCommand: pushFileCommand(buildConfigFile(config)),
    globalCommand: globalArgs(config),
    perSessionCommands: sessionNames.map((sessionName) => ({
      sessionName,
      command: perSessionArgs(config, sessionName),
    })),
  };
}
